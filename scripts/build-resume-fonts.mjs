// Regenerates src/resume/widths.ts (Cambria advance widths, which Word uses; Caladea is NOT exactly metric-identical,\n// its lowercase is ~5% narrower, so the PDF renderer stretches Caladea glyphs to these widths) and
// src/resume/fonts/fonts.ts (base64 of the Regular and Bold faces embedded by the PDF renderer).
// Usage: npm run resume:fonts
import fontkit from '@pdf-lib/fontkit';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'src', 'resume', 'fonts');
const load = (n) => fs.readFileSync(path.join(dir, `Caladea-${n}.ttf`));
const winFonts = process.env.WINDIR ? path.join(process.env.WINDIR, 'Fonts') : 'C:/Windows/Fonts';
const argAt = process.argv.indexOf('--cambria');
const cambriaDir = argAt > 0 ? process.argv[argAt + 1] : winFonts;
const cambria = (n) => {
  const p = path.join(cambriaDir, n === 'Regular' ? 'cambria.ttc' : 'cambriab.ttf');
  if (!fs.existsSync(p)) return null;
  const f = fontkit.create(fs.readFileSync(p));
  return f.fonts ? f.fonts[0] : f;
};
const codes = [];
for (let c = 32; c <= 126; c++) codes.push(c);
for (let c = 160; c <= 255; c++) codes.push(c);
codes.push(0x2013, 0x2014, 0x2022);

const table = (n) => {
  const cal = fontkit.create(load(n));
  const f = cambria(n) ?? cal;
  const out = {};
  for (const c of codes) {
    if (!f.hasGlyphForCodePoint(c) || !cal.hasGlyphForCodePoint(c)) continue;
    out[c] = Math.round((f.glyphForCodePoint(c).advanceWidth * 10000) / f.unitsPerEm) / 10;
  }
  return out;
};
const lit = (t) => '{' + Object.entries(t).map(([k, v]) => `${k}:${v}`).join(',') + '}';
const widths = `// Generated by scripts/build-resume-fonts.mjs. Advance widths per 1000 em of Cambria (what Word lays out with); falls back to Caladea when Cambria is not installed.
export const REG: Record<number, number> = ${lit(table('Regular'))};
export const BOLD: Record<number, number> = ${lit(table('Bold'))};
/** Cambria line height (hhea 1946+455 over 2048 units) as a multiple of the font size; Caladea's own vertical metrics differ. */
export const LINE_EM = 1.1719;
/** Ascent above the baseline as a multiple of the font size (Cambria, 1946/2048). */
export const ASCENT_EM = 0.9502;
`;
fs.writeFileSync(path.join(root, 'src', 'resume', 'widths.ts'), widths);
const b64 = (n) => load(n).toString('base64');
fs.writeFileSync(path.join(dir, 'fonts.ts'), `// Generated by scripts/build-resume-fonts.mjs. Caladea is licensed under the SIL OFL 1.1 (see OFL.txt).
export const CALADEA_REGULAR_B64 = '${b64('Regular')}';
export const CALADEA_BOLD_B64 = '${b64('Bold')}';
`);
console.log('widths.ts and fonts/fonts.ts written');
